package com.example.myapplication.navigation

/**
 * Pantallas del flujo de compra.
 *
 * Reemplaza la navegación con números mágicos (1, 2, 3...):
 * un `when` sobre este enum es exhaustivo y el compilador
 * avisa si falta alguna pantalla.
 */
enum class Pantalla {
    INICIO,
    CONVERSACION,
    RECOMENDACION,
    RESUMEN,
    CONFIRMACION
}
